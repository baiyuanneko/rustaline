const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const assert = require('node:assert/strict');
const context = { setTimeout, clearTimeout, AbortController, console, URL, fetch: async () => ({ok:true,json:async()=>({pow:{enabled:false},image:{enabled:false},reply_notification_enabled:true})}) };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.resolve(__dirname, '../../static/sdk/rustaline.js'), 'utf8'), context);
const Rustaline = context.Rustaline;
function setup() {
  const sdk = Object.create(Rustaline.prototype);
  const form = {querySelector:()=>null,_rs_refs:{textarea:{value:'草稿内容'},nickInput:{value:'作者'},mailInput:{value:''},linkInput:{value:''}}};
  Object.assign(sdk,{lang:Rustaline.langs['zh-CN'],opts:{server:'',url:'/test'},state:{},draft:{comment:'草稿内容',reply_notification:false},captcha:{configOk:true,supported:true,pow:{enabled:false},image:{enabled:false}},el:{querySelector:()=>form}});
  sdk._render = ()=>{};
  sdk._showFormError = (_form,msg)=>{sdk.error=msg};
  sdk._continueSubmit = body=>{sdk.sent=body};
  return {sdk,form};
}
const flush = ()=>new Promise(resolve=>setTimeout(resolve,20));
(async()=>{
  let {sdk,form}=setup(); let probes=0;
  sdk._probeCaptchaConfig=async()=>{probes++;return true};
  sdk._handleSubmit(form); await flush();
  assert.equal(probes,1,'每次提交都必须刷新配置，即使先前探测成功');
  assert.equal(sdk.sent.reply_notification,false,'取消邮件提醒必须进入提交正文');
  ({sdk,form}=setup()); sdk._probeCaptchaConfig=async()=>false;
  sdk._handleSubmit(form);await flush();
  assert.equal(sdk.sent,undefined,'已支持配置的新服务端断网时不得发评论');
  assert.equal(sdk.draft.comment,'草稿内容');assert.ok(sdk.error);
  ({sdk,form}=setup());sdk.captcha.supported=false;sdk.captcha.legacy=true;sdk.captcha.configOk=false;sdk._probeCaptchaConfig=async()=>false;
  sdk._handleSubmit(form);await flush();assert.ok(sdk.sent,'明确旧404服务端仍可提交');
  ({sdk}=setup());sdk._render=()=>{throw Error('探测配置不得重绘正在输入的表单')};
  assert.equal(await sdk._probeCaptchaConfig(5000),true);
  assert.equal(sdk.captcha.replyNotificationEnabled,true);
  ({sdk}=setup());
  context.fetch=async()=>({ok:true,json:()=>new Promise(()=>{})});
  assert.equal(await sdk._probeCaptchaConfig(10),false,'配置响应body卡住时仍必须限时');
  let posts=0,configs=0;
  context.fetch=async(_url,options)=>{
    if(options.method==='POST'){posts++;return {status:400,json:async()=>({message:'captcha code invalid'})};}
    configs++;return {ok:true,json:async()=>({pow:{enabled:false},image:{enabled:false}})};
  };
  ({sdk}=setup());
  Object.assign(sdk.state,{threads:[],rootTotal:0,count:0});
  sdk._dispatchSubmission({comment:'草稿内容'}, {id:'optimistic'}, {comment:'草稿内容',draftComment:' 草稿内容 '});
  sdk.draft.comment='用户正在写下一条';
  await flush();
  assert.equal(posts,1,'验证码失败绝不能自动重复POST');
  assert.equal(configs,1,'验证码失败要刷新后台开关');
  assert.equal(sdk.draft.comment,'用户正在写下一条','HTTP失败不能覆盖更新的输入');
  context.fetch=async()=>({ok:true,json:async()=>({pow:{enabled:false},image:{enabled:false},comment_max_length:20000})});
  ({sdk,form}=setup());
  form._rs_refs.textarea.value='字'.repeat(10001);
  sdk.captcha.commentMaxLength=1;
  sdk._handleSubmit(form);await flush();
  assert.equal(sdk.sent?.comment.length,10001,'必须先刷新，再允许后台增大后的正文上限');
  context.fetch=async()=>({ok:true,json:async()=>({pow:{enabled:false},image:{enabled:false},comment_max_length:2})});
  ({sdk,form}=setup());form._rs_refs.textarea.value='😀😀';
  sdk._handleSubmit(form);await flush();
  assert.equal(sdk.sent?.comment,'😀😀','emoji按Unicode码点计数，应与Rust chars一致');
  ({sdk,form}=setup());form._rs_refs.textarea.value='😀😀字';
  sdk._handleSubmit(form);await flush();
  assert.equal(sdk.sent,undefined,'后台低上限必须阻止提交');
  assert.ok(sdk.error.includes('2'),'长度错误必须显示真实上限');
  ({sdk,form}=setup());sdk.lang={...sdk.lang,commentTooLong:'自定义提示'};
  form._rs_refs.textarea.value='字字字';sdk._handleSubmit(form);await flush();
  assert.equal(sdk.error,'自定义提示','旧自定义字典不含模板仍须兼容');
  context.fetch=async()=>({ok:true,json:async()=>({pow:{enabled:false},image:{enabled:false},comment_max_length:'wrong'})});
  ({sdk}=setup());assert.equal(await sdk._probeCaptchaConfig(5000),true);
  assert.equal(sdk.captcha.commentMaxLength,10000,'缺失或非法上限须使用旧端默认值');
  context.fetch=async()=>({ok:true,json:async()=>({pow:{enabled:false},image:{enabled:false}})});
  ({sdk}=setup());assert.equal(await sdk._probeCaptchaConfig(5000),true);
  assert.equal(sdk.captcha.commentMaxLength,10000,'未提供正文上限的旧配置响应兼容默认10000');
  assert.deepEqual(Object.keys(Rustaline.langs['zh-CN']).sort(),Object.keys(Rustaline.langs.en).sort());
  console.log('SDK 回归：动态刷新、失败保留草稿、旧服务端兼容、通知偏好、配置无重绘、body限时、验证码失败不重复POST、新草稿保护、动态正文上限、Unicode码点、自定义字典、双语字典通过');
})().catch(err=>{console.error(err);process.exitCode=1});
